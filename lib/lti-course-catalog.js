export function getLtiCourse(courseKey) {
  return ltiCourses.find(course => course.key === courseKey) || null;
}

export function getLtiLesson(lessonId) {
  for (const course of ltiCourses) {
    const lesson = course.lessons.find(item => item.id === lessonId);
    if (lesson) return { ...lesson, courseKey: course.key, courseLabel: course.label };
  }
  return null;
}

export function getAllLtiLessons() {
  return ltiCourses.flatMap(course =>
    course.lessons.map(lesson => ({
      ...lesson,
      courseKey: course.key,
      courseLabel: course.label
    }))
  );
}
